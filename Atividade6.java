package AtividadeLista5While;

public class Atividade6 {
        public static void main(String[] args) {
            int cont = 0;
            int soma = 0;
            while(cont <= 9) {
                cont++;
                System.out.println(cont+"+"+soma);
                soma += cont;
                System.out.println(soma);

        }
    }
}
